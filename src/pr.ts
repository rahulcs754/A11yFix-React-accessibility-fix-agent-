import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

function run(cmd: string, args: string[], cwd: string): string {
  return execFileSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

export interface PrOptions {
  cwd: string;
  files: string[];
  title: string;
  body: string;
  base?: string;
}

/**
 * Creates a branch with only the fixed files, pushes it, and opens a PR with `gh`.
 * Returns the PR URL.
 */
export function openPullRequest({ cwd, files, title, body, base }: PrOptions): string {
  const top = run("git", ["rev-parse", "--show-toplevel"], cwd);
  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 12);
  const branch = `a11y-fix/${stamp}`;

  run("git", ["checkout", "-b", branch], top);
  run("git", ["add", "--", ...files.map((f) => path.relative(top, path.resolve(f)))], top);
  run("git", ["commit", "-m", title, "-m", "Generated by A11yFix."], top);
  run("git", ["push", "-u", "origin", branch], top);

  const bodyFile = path.join(mkdtempSync(path.join(tmpdir(), "a11y-fix-")), "body.md");
  writeFileSync(bodyFile, body);
  const args = ["pr", "create", "--title", title, "--body-file", bodyFile, "--head", branch];
  if (base) args.push("--base", base);
  return run("gh", args, top);
}
